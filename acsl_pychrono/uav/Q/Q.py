    l_x = float(cfg["uav"]["mixer_matrix"]["l_x"]) 
    l_y = float(cfg["uav"]["mixer_matrix"]["l_y"])
    c_t = float(cfg["uav"]["mixer_matrix"]["c_t"])

    # Mixer matrix for QUADcopter 
    # U_mat = np.array([[ 1,    1,    1,    1  ], 
    #                   [ l_y,  l_y, -l_y, -l_y],
    #                   [-l_x,  l_x,  l_x, -l_x],
    #                   [-c_t,  c_t, -c_t,  c_t]])
    # Mixer matrix for QUADcopter 
